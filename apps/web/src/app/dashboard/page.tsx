function todayIsoDate(): string {
  return new Date().toISOString().slice(0, 10);
}

function ExecutiveKpiPanel() {
  const { session } = useAuth();
  const [date, setDate] = useState(todayIsoDate);
  const [data, setData] = useState<ExecutiveKpis | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [downloadError, setDownloadError] = useState<string | null>(null);
  const [downloading, setDownloading] = useState(false);
  const [downloadingExcel, setDownloadingExcel] = useState(false);

  useEffect(() => {
    if (session?.role !== "admin" || session.mode === "local-dev") return;

    let cancelled = false;

    const load = async () => {
      const result = await apiClient.getExecutiveKpis(date);
      if (cancelled) return;

      if (result.error || !result.data) {
        setError(result.error || "Không tải được KPI lãnh đạo");
        setData(null);
        return;
      }

      setError(null);
      setData(result.data);
    };

    void load();
    const timer = window.setInterval(() => {
      void load();
    }, 60_000);

    return () => {
      cancelled = true;
      window.clearInterval(timer);
    };
  }, [date, session?.mode, session?.role]);

  if (session?.role !== "admin" || session.mode === "local-dev") return null;

  const handleDownloadReport = async () => {
    setDownloading(true);
    setDownloadError(null);
    const result = await apiClient.downloadExecutiveReportCsv(date);
    setDownloading(false);

    if (result.error || !result.data) {
      setDownloadError(result.error || "Không tải được báo cáo KPI");
      return;
    }

    const url = window.URL.createObjectURL(result.data);
    const link = document.createElement("a");
    link.href = url;
    link.download = `ttport-executive-kpi-${date}.csv`;
    document.body.appendChild(link);
    link.click();
    link.remove();
    window.URL.revokeObjectURL(url);
  };

  const handleDownloadExcelReport = async () => {
    setDownloadingExcel(true);
    setDownloadError(null);
    const result = await apiClient.getExecutiveReportPack(date);
    setDownloadingExcel(false);

    if (result.error || !result.data) {
      setDownloadError(result.error || "Không tải được báo cáo KPI Excel");
      return;
    }

    const report = result.data;
    const summaryRows = [
      { Chỉ_số: "Generated At", Giá_trị: report.generatedAt },
      { Chỉ_số: "Generated By", Giá_trị: report.generatedBy },
      { Chỉ_số: "Start Date", Giá_trị: report.period.startDate },
      { Chỉ_số: "End Date", Giá_trị: report.period.endDate },
      { Chỉ_số: "Total In", Giá_trị: report.summary.total_in },
      { Chỉ_số: "Total Out", Giá_trị: report.summary.total_out },
      { Chỉ_số: "Total CFS", Giá_trị: report.summary.total_cfs },
      { Chỉ_số: "Total Moves", Giá_trị: report.summary.total_moves },
      { Chỉ_số: "Vessel Moves", Giá_trị: report.summary.vessel_moves },
      { Chỉ_số: "Vessel TEUs", Giá_trị: report.summary.vessel_teus },
      { Chỉ_số: "Report Count", Giá_trị: report.summary.report_count },
      { Chỉ_số: "Leave Requests", Giá_trị: report.summary.leave_requests },
    ];

    const detailRows = report.rows.map((row) => ({
      Ngày: row.date,
      "Vào": row.total_in,
      "Ra": row.total_out,
      CFS: row.total_cfs,
      "Tổng biến động": row.total_moves,
      "Moves tàu": row.vessel_moves,
      TEUs: row.vessel_teus,
      "Số báo cáo": row.report_count,
      "Nghỉ phép": row.leave_requests,
    }));

    const workbook = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(
      workbook,
      XLSX.utils.json_to_sheet(summaryRows),
      "Summary"
    );
    XLSX.utils.book_append_sheet(
      workbook,
      XLSX.utils.json_to_sheet(detailRows),
      "Daily Detail"
    );
    XLSX.writeFile(workbook, `ttport-executive-kpi-${date}.xlsx`);
  };

  if (error) {
    return (
      <div className="mb-6 rounded-xl border border-yellow-400/30 bg-yellow-400/10 p-4 text-sm text-yellow-200">
        {error}
      </div>
    );
  }

  const cards: {
    label: string;
    value: number;
    suffix?: string;
    hint: string;
    Icon: LucideIcon;
    tone: KPITone;
  }[] = [
    {
      label: "Sản lượng ngày",
      value: data?.daily.totalMoves ?? 0,
      hint: `Vào ${data?.daily.totalIn ?? 0} / Ra ${data?.daily.totalOut ?? 0}`,
      Icon: BarChart3,
      tone: "accent",
    },
    {
      label: "Lũy kế tháng",
      value: data?.monthToDate.totalMoves ?? 0,
      hint: `${data?.monthToDate.reportCount ?? 0} báo cáo đã nộp`,
      Icon: TrendingUp,
      tone: "success",
    },
    {
      label: "Tàu / TEUs ngày",
      value: data?.daily.vesselMoves ?? 0,
      hint: `${data?.daily.vesselTeus ?? 0} TEUs`,
      Icon: Ship,
      tone: "info",
    },
    {
      label: "Nhân sự hoạt động",
      value: data?.workforce.activeEmployees ?? 0,
      hint: `${data?.workforce.departments ?? 0} bộ phận / ${data?.workforce.shifts ?? 0} ca`,
      Icon: Users,
      tone: "warning",
    },
    {
      label: "Hoàn tất báo cáo",
      value: data?.daily.reportCompletionRate ?? 0,
      suffix: "%",
      hint: `${data?.daily.leaveRequests ?? 0} đơn nghỉ phép`,
      Icon: ClipboardCheck,
      tone: "success",
    },
  ];

  return (
    <section className="mb-6">
      <div className="mb-4 flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
        <div>
          <p className="text-xs font-semibold uppercase tracking-wider text-[var(--color-text-muted)]">
            KPI lãnh đạo
          </p>
          <h3 className="mt-0.5 text-xl font-semibold text-[var(--color-text-primary)]">
            Tổng quan ngày, tháng và nhân sự
          </h3>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <input
            type="date"
            aria-label="Chọn ngày"
            value={date}
            onChange={(event) => setDate(event.target.value)}
            className="cvf-input h-9 rounded-lg px-3 text-sm"
          />
          <Button
            variant="secondary"
            icon={Download}
            onClick={handleDownloadReport}
            disabled={downloading}
          >
            {downloading ? "Đang tải" : "Tải KPI CSV"}
          </Button>
          <Button
            variant="primary"
            icon={Download}
            onClick={handleDownloadExcelReport}
            disabled={downloadingExcel}
          >
            {downloadingExcel ? "Đang tạo" : "Tải KPI Excel"}
          </Button>
        </div>
      </div>

      {downloadError && (
        <div className="mb-3 rounded-lg border border-yellow-400/30 bg-yellow-400/10 p-3 text-sm text-yellow-200">
          {downloadError}
        </div>
      )}

      <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-5">
        {cards.map((card) => (
          <KPICard
            key={card.label}
            icon={card.Icon}
            label={card.label}
            value={`${card.value.toLocaleString("vi-VN")}${card.suffix ?? ""}`}
            tone={card.tone}
            hint={card.hint}
          />
        ))}
      </div>
    </section>
  );
}

