export default function DashboardPage() {
  const [dashboardMode, setDashboardMode] = useState<DashboardMode>("monthly");
  const [activeTab, setActiveTab] = useState<PeriodType>("month");
  const [dailyData, setDailyData] = useState<DashboardData[]>([]);
  const [monthlyData, setMonthlyData] = useState<DashboardData[]>([]);
  const [hasRealData, setHasRealData] = useState({
    daily: false,
    monthly: false,
  });

  // Hourly throughput (today's date)
  const [hourlyData, setHourlyData] = useState<{ hour: number; teus: number }[]>([]);

  // Pagination state for daily view
  const [dailyPage, setDailyPage] = useState(1);

  // Date filter state
  const [dateFilter, setDateFilter] = useState<DateFilterValue>({
    year: getCurrentYear(),
  });

  // Date range state for advanced filtering
  const [dateRange, setDateRange] = useState<DateRange>({
    startDate: null,
    endDate: null,
  });

  // Drilldown state for modal
  const [drilldown, setDrilldown] = useState<{
    isOpen: boolean;
    month: number;
    label: string;
  }>({
    isOpen: false,
    month: 0,
    label: "",
  });

  // Handle drill-down click (for monthly data)
  const handleDrilldown = useCallback((month: number, label: string) => {
    setDrilldown({ isOpen: true, month, label });
  }, []);

  const closeDrilldown = useCallback(() => {
    setDrilldown((prev) => ({ ...prev, isOpen: false }));
  }, []);

  // Handle filter change - reset page when filter changes
  const handleFilterChange = useCallback((filter: DateFilterValue) => {
    setDateFilter(filter);
    setDailyPage(1); // Reset to page 1
    setDateRange({ startDate: null, endDate: null }); // Clear date range
  }, []);

  // Load data from IndexedDB using hooks
  const dbDailyData = useDailyData(dateFilter.year, dateFilter.month);
  const dbMonthlyData = useMonthlyData(dateFilter.year);
  const dbStatus = useDbStatus();

  // YoY Comparison data
  const yoyMonthData = useYoYComparison(
    dateFilter.month || new Date().getMonth() + 1,
    3
  );
  const yoyQuarterData = useYoYComparisonQuarter(dateFilter.quarter || 1, 3);
  const yoyYearData = useYoYComparisonYear(3);

  // Load hourly data on mount
  useEffect(() => {
    setHourlyData(getThroughputByHour(todayIsoDate()));
  }, []);

  // Load from localStorage on mount (fallback)
  useEffect(() => {
    const savedDaily = loadFromStorage("daily");
    const savedMonthly = loadFromStorage("monthly");

    if (savedDaily && savedDaily.length > 0) {
      setDailyData(savedDaily);
      setHasRealData((prev) => ({ ...prev, daily: true }));
    } else {
      setDailyData(DEMO_DAILY);
    }

    if (savedMonthly && savedMonthly.length > 0) {
      setMonthlyData(savedMonthly);
      setHasRealData((prev) => ({ ...prev, monthly: true }));
    } else {
      setMonthlyData(DEMO_MONTHLY);
    }
  }, []);

  // Determine if using DB data
  const hasDbData = dbStatus?.hasData || false;

  // Get current data based on mode - prefer IndexedDB if available
  const currentData = useMemo(() => {
    if (dashboardMode === "daily") {
      // Use DB data if available
      if (dbDailyData && dbDailyData.length > 0) {
        // Convert DB format to DashboardData format
        return dbDailyData.map((d) => ({
          id: d.id?.toString() || `day-${d.day}`,
          period: d.day.toString().padStart(2, "0"),
          periodType: "day" as PeriodType,
          label: `Ngày ${d.day.toString().padStart(2, "0")}`,
          tongBienDong: d.total,
          tongCont: d.total,
          xe: {
            ha: d.xe_ha,
            giao: d.xe_giao,
            // xe_dh = đóng hàng (full CFS), xe_rr = rút ruột (empty CFS)
            // Fallback: split xe_cfs evenly if detail fields not available
            fullCfs: d.xe_dh ?? Math.floor(d.xe_cfs / 2),
            emptyCfs: d.xe_rr ?? Math.ceil(d.xe_cfs / 2),
            total: d.xe_total,
          },
          xalan: {
            ha: d.xalan_ha,
            giao: d.xalan_giao,
            fullCfs: d.xalan_dh ?? Math.floor(d.xalan_cfs / 2),
            emptyCfs: d.xalan_rr ?? Math.ceil(d.xalan_cfs / 2),
            total: d.xalan_total,
          },
          cfs: {
            // total_cfs is the combined CFS total; split if detail not available
            full: (d.xe_dh ?? 0) + (d.xalan_dh ?? 0) || Math.floor(d.total_cfs / 2),
            empty: (d.xe_rr ?? 0) + (d.xalan_rr ?? 0) || Math.ceil(d.total_cfs / 2),
          },
        }));
      }
      return dailyData;
    } else {
      // Monthly mode - use DB data if available
      if (dbMonthlyData && dbMonthlyData.length > 0) {
        // Filter by month/quarter if specified
        let filtered = dbMonthlyData;
        if (dateFilter.month) {
          filtered = filtered.filter((d) => d.month === dateFilter.month);
        }
        if (dateFilter.quarter) {
          filtered = filtered.filter((d) => d.quarter === dateFilter.quarter);
        }

        return filtered.map((d) => ({
          id: d.id?.toString() || `month-${d.year}-${d.month}`,
          period: `T${d.month.toString().padStart(2, "0")}`,
          periodType: "month" as PeriodType,
          label:
            dateFilter.month || dateFilter.quarter
              ? `T${d.month.toString().padStart(2, "0")}/${d.year}`
              : `T${d.month.toString().padStart(2, "0")}`,
          tongBienDong: d.total,
          tongCont: d.total,
          xe: {
            ha: d.xe_ha,
            giao: d.xe_giao,
            // xe_cfs is total CFS; monthly summary doesn't have dh/rr breakdown
            fullCfs: Math.floor(d.xe_cfs / 2),
            emptyCfs: Math.ceil(d.xe_cfs / 2),
            total: d.xe_total,
          },
          xalan: {
            ha: d.xalan_ha,
            giao: d.xalan_giao,
            fullCfs: Math.floor(d.xalan_cfs / 2),
            emptyCfs: Math.ceil(d.xalan_cfs / 2),
            total: d.xalan_total,
          },
          cfs: {
            full: Math.floor(d.total_cfs / 2),
            empty: Math.ceil(d.total_cfs / 2),
          },
        }));
      }
      // Fallback to localStorage - filter by selected year if possible
      // Note: localStorage data doesn't have year info, so return all
      return monthlyData;
    }
  }, [
    dashboardMode,
    dailyData,
    monthlyData,
    dbDailyData,
    dbMonthlyData,
    dateFilter,
  ]);

  const isUsingDemo =
    !hasDbData &&
    (dashboardMode === "daily" ? !hasRealData.daily : !hasRealData.monthly);

  // Filter data by period type (for tabs)
  const filteredData = useMemo(() => {
    if (dashboardMode === "daily") {
      return currentData;
    }
    if (activeTab === "cumulative") {
      return currentData.filter(
        (d) => d.periodType === "cumulative" || d.periodType === "year"
      );
    }
    return currentData.filter((d) => d.periodType === activeTab);
  }, [currentData, activeTab, dashboardMode]);

  // Calculate summary
  const summary: DashboardSummary = useMemo(() => {
    const total = filteredData.reduce(
      (acc, d) => ({
        xeTotal: acc.xeTotal + d.xe.total,
        xalanTotal: acc.xalanTotal + d.xalan.total,
      }),
      { xeTotal: 0, xalanTotal: 0 }
    );

    const grandTotal = total.xeTotal + total.xalanTotal;

    return {
      totalIn: filteredData.reduce((acc, d) => acc + d.xe.ha + d.xalan.ha, 0),
      totalOut: filteredData.reduce(
        (acc, d) => acc + d.xe.giao + d.xalan.giao,
        0
      ),
      xeTotal: total.xeTotal,
      xalanTotal: total.xalanTotal,
      xePercent: grandTotal > 0 ? (total.xeTotal / grandTotal) * 100 : 0,
      xalanPercent: grandTotal > 0 ? (total.xalanTotal / grandTotal) * 100 : 0,
    };
  }, [filteredData]);

  // Cargo classification breakdown (Hạ / Giao / CFS In / CFS Out)
  const cargoSummary = useMemo(() => ({
    ha:     filteredData.reduce((acc, d) => acc + d.xe.ha     + d.xalan.ha,     0),
    giao:   filteredData.reduce((acc, d) => acc + d.xe.giao   + d.xalan.giao,   0),
    cfsIn:  filteredData.reduce((acc, d) => acc + d.xe.fullCfs  + d.xalan.fullCfs,  0),
    cfsOut: filteredData.reduce((acc, d) => acc + d.xe.emptyCfs + d.xalan.emptyCfs, 0),
  }), [filteredData]);

  // Chart data - paginate for daily mode
  const chartData = useMemo(() => {
    if (dashboardMode === "daily") {
      // Apply pagination for daily
      const start = (dailyPage - 1) * DAILY_PAGE_SIZE;
      const end = start + DAILY_PAGE_SIZE;
      const paginatedData = filteredData.slice(start, end);
      return paginatedData.map((d) => ({
        label: d.label,
        xe: d.xe.total,
        xalan: d.xalan.total,
      }));
    }
    // No pagination for monthly
    return filteredData.map((d) => ({
      label: d.label,
      xe: d.xe.total,
      xalan: d.xalan.total,
    }));
  }, [filteredData, dashboardMode, dailyPage]);

  // Pagination info for daily
  const dailyPagination = useMemo(() => {
    if (dashboardMode !== "daily") return null;
    const totalItems = filteredData.length;
    const totalPages = Math.ceil(totalItems / DAILY_PAGE_SIZE);
    return { totalItems, totalPages, currentPage: dailyPage };
  }, [dashboardMode, filteredData.length, dailyPage]);

  // Data for cumulative chart (needs xe_total, xalan_total, total format)
  const cumulativeChartData = useMemo(() => {
    return filteredData.map((d) => ({
      label: d.label,
      xe_total: d.xe.total,
      xalan_total: d.xalan.total,
      total: d.xe.total + d.xalan.total,
    }));
  }, [filteredData]);

  // Switch dashboard mode - reset page
  const handleModeChange = (mode: DashboardMode) => {
    setDashboardMode(mode);
    setActiveTab(mode === "daily" ? "day" : "month");
    setDailyPage(1); // Reset page when switching mode
  };

  // Available tabs for current mode
  const availableTabs = PERIOD_TABS.filter((t) => t.mode === dashboardMode);
  const periodContext =
    dashboardMode === "daily"
      ? dateFilter.month
        ? `Ngày / T${dateFilter.month.toString().padStart(2, "0")}/${dateFilter.year}`
        : `Ngày / ${dateFilter.year}`
      : dateFilter.month
        ? `T${dateFilter.month.toString().padStart(2, "0")}/${dateFilter.year}`
        : dateFilter.quarter
          ? `Q${dateFilter.quarter}/${dateFilter.year}`
          : `${dateFilter.year}`;

  return (
    <div>
      <div>
        <div className="mb-5 flex flex-col gap-3 md:flex-row md:items-center md:justify-between">
          <div>
            <p className="text-sm font-medium text-[var(--color-text-secondary)]">
              Bức tranh vận hành container
            </p>
            <h2 className="text-2xl font-semibold text-[var(--color-text-primary)]">
              Theo dõi biến động vào/ra
            </h2>
          </div>
          <span className="w-fit rounded-full border border-[var(--color-border)] bg-[var(--color-accent-dim)] px-3 py-1.5 text-sm font-semibold text-[var(--color-text-primary)]">
            {periodContext}
          </span>
        </div>

        <ExecutiveKpiPanel />

        <AlertsPanel date={todayIsoDate()} />

        {/* Dashboard Mode Switcher */}
        <div className="flex items-center gap-4 mb-4">
          <span className="text-[var(--color-text-secondary)] text-sm">Chọn Dashboard:</span>
          <div className="flex rounded-xl bg-[var(--color-surface)] p-1 ring-1 ring-[var(--color-border)]">
            <button
              onClick={() => handleModeChange("daily")}
              className={`px-4 py-2 rounded-lg transition-all font-medium ${
                dashboardMode === "daily"
                  ? "bg-[var(--color-accent)] text-white shadow-lg"
                  : "text-[var(--color-text-secondary)] hover:text-white"
              }`}
            >
              Biến Động Ngày
            </button>
            <button
              onClick={() => handleModeChange("monthly")}
              className={`px-4 py-2 rounded-lg transition-all font-medium ${
                dashboardMode === "monthly"
                  ? "bg-[var(--color-accent)] text-white shadow-lg"
                  : "text-[var(--color-text-secondary)] hover:text-white"
              }`}
            >
              Biến Động Tháng/Năm
            </button>
          </div>

          {/* Data status */}
          <span
            className={`text-xs px-2 py-1 rounded ${
              isUsingDemo
                ? "bg-amber-900/50 text-amber-400"
                : "bg-green-900/50 text-green-400"
            }`}
          >
            {isUsingDemo ? "⚠️ Demo" : "✓ Dữ liệu thực"}
          </span>
        </div>

        {/* Advanced Filters Row */}
        <div className="flex flex-wrap items-center gap-3 mb-4">
          {/* Date Range Picker */}
          <DateRangePicker value={dateRange} onChange={setDateRange} />
        </div>

        {/* Period Tabs (only for monthly mode) */}
        {dashboardMode === "monthly" && (
          <div className="flex flex-wrap gap-2 mb-6 bg-gray-800/50 p-2 rounded-xl">
            {availableTabs.map((tab) => {
              const Icon = tab.icon;
              return (
                <button
                  key={tab.key}
                  onClick={() => setActiveTab(tab.key)}
                  className={`flex items-center gap-2 px-4 py-2 rounded-lg transition-all ${
                    activeTab === tab.key
                      ? "bg-[var(--color-accent)] text-white shadow-lg"
                      : "bg-[var(--color-bg)]/50 text-[var(--color-text-secondary)] hover:bg-[var(--color-elevated)] hover:text-white"
                  }`}
                >
                  <Icon className="h-4 w-4" aria-hidden="true" />
                  <span className="hidden sm:inline">{tab.label}</span>
                </button>
              );
            })}
          </div>
        )}

        {/* Date Filter */}
        <DateFilter onFilterChange={handleFilterChange} mode={dashboardMode} />

        {/* No Data Warning */}
        {filteredData.length === 0 && hasDbData && (
          <div className="mb-6 p-4 bg-amber-900/30 border border-amber-600/50 rounded-xl flex items-center gap-3">
            <span className="text-2xl">⚠️</span>
            <div>
              <p className="text-amber-400 font-medium">
                Không có dữ liệu cho thời gian đã chọn
              </p>
              <p className="text-amber-300/70 text-sm">
                Vui lòng kiểm tra lại bộ lọc hoặc upload thêm dữ liệu.
                {dateFilter.month &&
                  ` Tháng ${dateFilter.month}/${dateFilter.year} chưa có dữ liệu.`}
                {dateFilter.quarter &&
                  ` Quý ${dateFilter.quarter}/${dateFilter.year} chưa có dữ liệu.`}
                {!dateFilter.month &&
                  !dateFilter.quarter &&
                  ` Năm ${dateFilter.year} chưa có dữ liệu.`}
              </p>
            </div>
          </div>
        )}

        {/* KPI Cards */}
        <div className="mb-6">
          <KPICards summary={summary} />
        </div>

        {/* Charts Row */}
        <div className="grid grid-cols-1 lg:grid-cols-3 gap-6 mb-6">
          {/* Bar Chart - 2/3 width */}
          <div className="lg:col-span-2">
            <BarChart
              data={chartData}
              title={`📊 Biến Động theo ${
                dashboardMode === "daily"
                  ? "Ngày"
                  : availableTabs.find((t) => t.key === activeTab)?.label ||
                    "Thời gian"
              }`}
            />
          </div>

          {/* Pie + CargoDonut stacked - 1/3 width */}
          <div className="flex flex-col gap-4">
            <PieChart xe={summary.xeTotal} xalan={summary.xalanTotal} />
            <CargoDonut
              ha={cargoSummary.ha}
              giao={cargoSummary.giao}
              cfsIn={cargoSummary.cfsIn}
              cfsOut={cargoSummary.cfsOut}
            />
          </div>
        </div>

        {/* Hourly throughput — daily mode only */}
        {dashboardMode === "daily" && (
          <div className="mb-6">
            <HourlyChart data={hourlyData} />
          </div>
        )}

        {/* Cumulative Chart - shows when Lũy Tiến tab is active */}
        {activeTab === "cumulative" && cumulativeChartData.length > 0 && (
          <div className="mb-6">
            <CumulativeChart
              data={cumulativeChartData}
              title={`Lũy Tiến theo Tháng`}
            />
          </div>
        )}

        {/* YoY Comparison Charts */}
        {dashboardMode === "monthly" && (
          <div className="mb-6">
            {/* YoY for specific month */}
            {dateFilter.month && (
              <YoYComparisonChart
                data={yoyMonthData}
                month={dateFilter.month}
                title={`📈 So sánh cùng kỳ Tháng ${dateFilter.month} (3 năm)`}
              />
            )}

            {/* YoY for specific quarter */}
            {!dateFilter.month &&
              dateFilter.quarter &&
              yoyQuarterData &&
              yoyQuarterData.length > 0 && (
                <div className="bg-gray-800/50 rounded-xl p-6">
                  <h3 className="text-lg font-semibold text-white mb-4">
                    📊 So sánh Quý {dateFilter.quarter} (3 năm gần nhất)
                  </h3>
                  <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
                    {yoyQuarterData.map((item) => (
                      <div
                        key={item.year}
                        className="bg-gray-900/50 rounded-lg p-4 text-center"
                      >
                        <p className="text-gray-400 text-sm">Năm {item.year}</p>
                        <p className="text-2xl font-bold text-white">
                          {item.total.toLocaleString()}
                        </p>
                        <div className="flex justify-center gap-4 mt-2 text-sm">
                          <span className="text-orange-400">
                            XE: {item.xe_total.toLocaleString()}
                          </span>
                          <span className="text-purple-400">
                            XALAN: {item.xalan_total.toLocaleString()}
                          </span>
                        </div>
                      </div>
                    ))}
                  </div>
                </div>
              )}

            {/* YoY for full year comparison */}
            {!dateFilter.month &&
              !dateFilter.quarter &&
              yoyYearData &&
              yoyYearData.length > 0 && (
                <div className="bg-gray-800/50 rounded-xl p-6">
                  <h3 className="text-lg font-semibold text-white mb-4">
                    📊 So sánh Năm (3 năm gần nhất)
                  </h3>
                  <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
                    {yoyYearData.map((item, idx) => {
                      const prevItem = yoyYearData[idx - 1];
                      const change = prevItem
                        ? ((item.total - prevItem.total) / prevItem.total) * 100
                        : 0;
                      return (
                        <div
                          key={item.year}
                          className="bg-gray-900/50 rounded-lg p-4 text-center"
                        >
                          <p className="text-gray-400 text-sm">
                            Năm {item.year}
                          </p>
                          <p className="text-2xl font-bold text-white">
                            {item.total.toLocaleString()}
                          </p>
                          {prevItem && (
                            <p
                              className={`text-sm mt-1 ${
                                change >= 0 ? "text-green-400" : "text-red-400"
                              }`}
                            >
                              {change >= 0 ? "▲" : "▼"}{" "}
                              {Math.abs(change).toFixed(1)}% so với{" "}
                              {item.year - 1}
                            </p>
                          )}
                          <div className="flex justify-center gap-4 mt-2 text-sm">
                            <span className="text-orange-400">
                              XE: {item.xe_total.toLocaleString()}
                            </span>
                            <span className="text-purple-400">
                              XALAN: {item.xalan_total.toLocaleString()}
                            </span>
                          </div>
                        </div>
                      );
                    })}
                  </div>
                </div>
              )}
          </div>
        )}

        {/* Pagination for Daily Mode */}
        {dailyPagination && dailyPagination.totalPages > 1 && (
          <div className="mb-4 flex items-center justify-center gap-3">
            <span className="text-gray-400 text-sm">
              Trang {dailyPagination.currentPage}/{dailyPagination.totalPages}(
              {dailyPagination.totalItems} ngày)
            </span>
            <div className="flex gap-2">
              <button
                onClick={() => setDailyPage((p) => Math.max(1, p - 1))}
                disabled={dailyPage === 1}
                className="px-3 py-1.5 rounded bg-gray-700 text-white text-sm
                                         disabled:opacity-50 disabled:cursor-not-allowed
                                         hover:bg-gray-600 transition-colors"
              >
                ‹ Trước
              </button>
              {Array.from(
                { length: dailyPagination.totalPages },
                (_, i) => i + 1
              ).map((page) => (
                <button
                  key={page}
                  onClick={() => setDailyPage(page)}
                  className={`px-3 py-1.5 rounded text-sm font-medium transition-colors
                                              ${
                                                dailyPage === page
                                                  ? "bg-blue-600 text-white"
                                                  : "bg-gray-700 text-gray-300 hover:bg-gray-600"
                                              }`}
                >
                  {page}
                </button>
              ))}
              <button
                onClick={() =>
                  setDailyPage((p) =>
                    Math.min(dailyPagination.totalPages, p + 1)
                  )
                }
                disabled={dailyPage === dailyPagination.totalPages}
                className="px-3 py-1.5 rounded bg-gray-700 text-white text-sm
                                         disabled:opacity-50 disabled:cursor-not-allowed
                                         hover:bg-gray-600 transition-colors"
              >
                Sau ›
              </button>
            </div>
          </div>
        )}

        {/* Data Table */}
        <DataTable
          data={
            dashboardMode === "daily"
              ? filteredData.slice(
                  (dailyPage - 1) * DAILY_PAGE_SIZE,
                  dailyPage * DAILY_PAGE_SIZE
                )
              : filteredData
          }
          pageSize={dashboardMode === "daily" ? 100 : 10} // Disable internal pagination for daily
          onRowClick={
            dashboardMode === "monthly"
              ? (item) => {
                  // Extract month number from period like "T01", "T02", etc.
                  const monthMatch = item.period.match(/\d+/);
                  if (monthMatch) {
                    const monthNum = parseInt(monthMatch[0], 10);
                    handleDrilldown(monthNum, item.label);
                  }
                }
              : undefined
          }
        />
      </div>

      {/* Drilldown Modal */}
      <DrilldownModal
        isOpen={drilldown.isOpen}
        onClose={closeDrilldown}
        year={dateFilter.year}
        month={drilldown.month}
        monthLabel={drilldown.label}
      />
    </div>
  );
}
